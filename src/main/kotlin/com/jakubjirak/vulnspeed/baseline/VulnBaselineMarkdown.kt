package com.jakubjirak.vulnspeed.baseline

import com.jakubjirak.vulnspeed.model.Severity
import com.jakubjirak.vulnspeed.model.Vulnerability

/**
 * Renders a [VulnBaselineDiff] as a PR-comment-ready Markdown document.
 *
 * Tables are escaped so that pipes and backticks in finding messages or paths
 * cannot break layout. When a severity bucket has more than
 * [COLLAPSIBLE_THRESHOLD] rows the body is wrapped in `<details>` so reviewers
 * see a compact summary by default.
 */
object VulnBaselineMarkdown {

    /** Maximum rows rendered inline before a severity section collapses. */
    const val COLLAPSIBLE_THRESHOLD: Int = 10

    /**
     * Render a Markdown report.
     *
     * @param diff the diff to render.
     * @param toolVersion VulnSpeed version to cite in the footer.
     * @param title optional document title. Defaults to a banner selected by
     *              [VulnBaselineDiff.hasRegressions].
     */
    fun render(
        diff: VulnBaselineDiff,
        toolVersion: String = "",
        title: String? = null,
    ): String {
        val buf = StringBuilder()
        val banner = title ?: if (diff.hasRegressions()) {
            "# 🚨 VulnSpeed — Security Baseline Regressions Detected"
        } else {
            "# ✅ VulnSpeed — No New Regressions vs Baseline"
        }
        buf.appendLine(banner).appendLine()

        val s = diff.summary
        buf.appendLine("**Summary**")
        buf.appendLine()
        buf.appendLine("| Metric | Count |")
        buf.appendLine("|---|---:|")
        buf.appendLine("| 🆕 New regressions | ${s.totalNew} |")
        buf.appendLine("| ♻️ Persisted (baselined) | ${s.totalPersisted} |")
        buf.appendLine("| ✅ Fixed since baseline | ${s.totalFixed} |")
        for (sev in Severity.entries) {
            val c = s.newBySeverity[sev.name] ?: 0
            if (c > 0) buf.appendLine("| New ${sev.name} | $c |")
        }
        buf.appendLine()

        if (diff.newFindings.isEmpty()) {
            buf.appendLine("_No new regressions were introduced. 🎉_").appendLine()
        } else {
            buf.appendLine("## New regressions").appendLine()
            for (sev in Severity.entries) {
                val bucket = diff.newFindings.filter { it.severity == sev }
                if (bucket.isEmpty()) continue
                renderBucket(buf, sev, bucket)
            }
        }

        if (diff.fixedEntries.isNotEmpty()) {
            buf.appendLine("## Fixed since baseline").appendLine()
            buf.appendLine("| Rule | CWE | File | Line |")
            buf.appendLine("|---|---:|---|---:|")
            for (e in diff.fixedEntries) {
                buf.appendLine(
                    "| ${escape(e.ruleId)} | ${e.cwe} | ${escape(e.filePath)} | ${e.startLine} |"
                )
            }
            buf.appendLine()
        }

        buf.appendLine("---")
        buf.appendLine(
            "_Generated by VulnSpeed${if (toolVersion.isNotBlank()) " " + toolVersion else ""} " +
                "— Security Baseline & Differential Scan._"
        )
        return buf.toString()
    }

    private fun renderBucket(buf: StringBuilder, sev: Severity, bucket: List<Vulnerability>) {
        val collapsible = bucket.size > COLLAPSIBLE_THRESHOLD
        if (collapsible) {
            buf.appendLine("<details>")
            buf.appendLine("<summary><b>${sev.name}</b> — ${bucket.size} finding(s)</summary>")
            buf.appendLine()
        } else {
            buf.appendLine("### ${sev.name} — ${bucket.size} finding(s)")
            buf.appendLine()
        }
        buf.appendLine("| Rule | CWE | File:Line | Message |")
        buf.appendLine("|---|---:|---|---|")
        for (v in bucket) {
            val fileLine = "${escape(v.filePath)}:${v.line}"
            buf.appendLine(
                "| ${escape(v.ruleId)} | ${v.cwe} | $fileLine | ${escape(v.message)} |"
            )
        }
        buf.appendLine()
        if (collapsible) {
            buf.appendLine("</details>")
            buf.appendLine()
        }
    }

    /** Escape characters that would otherwise break a Markdown table cell. */
    fun escape(raw: String): String {
        val sb = StringBuilder(raw.length + 8)
        for (ch in raw) {
            when (ch) {
                '|' -> sb.append("\\|")
                '`' -> sb.append("\\`")
                '\\' -> sb.append("\\\\")
                '\n', '\r' -> sb.append(' ')
                else -> sb.append(ch)
            }
        }
        return sb.toString()
    }
}
