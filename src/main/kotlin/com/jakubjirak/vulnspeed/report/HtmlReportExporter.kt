package com.jakubjirak.vulnspeed.report

import com.jakubjirak.vulnspeed.model.ScanResult
import com.jakubjirak.vulnspeed.model.Severity
import com.jakubjirak.vulnspeed.model.Vulnerability
import java.text.SimpleDateFormat
import java.util.Date
import java.util.Locale

/**
 * Renders a scan result as a single self-contained HTML report — no external
 * assets, safe to attach to a ticket or email to a security team.
 */
class HtmlReportExporter {

    /**
     * Builds the full HTML document for [result].
     *
     * @param projectName display name shown in the report header
     * @param toolVersion plugin version shown in the footer
     */
    fun export(result: ScanResult, projectName: String, toolVersion: String = "dev"): String {
        val findings = result.vulnerabilities
        val date = SimpleDateFormat("yyyy-MM-dd HH:mm", Locale.US).format(Date(result.timestamp))

        return buildString {
            append("<!DOCTYPE html>\n")
            append("<html lang=\"en\">\n<head>\n<meta charset=\"utf-8\">\n")
            append("<meta name=\"viewport\" content=\"width=device-width, initial-scale=1\">\n")
            append("<title>VulnSpeed Security Report — ").append(escape(projectName)).append("</title>\n")
            append("<style>").append(CSS).append("</style>\n</head>\n<body>\n")

            append("<header><h1>VulnSpeed Security Report</h1>")
            append("<p class=\"meta\">Project: <b>").append(escape(projectName)).append("</b>")
            append(" &middot; Generated: ").append(escape(date))
            append(" &middot; Scan duration: ").append(result.durationMs).append(" ms</p></header>\n")

            append("<section class=\"cards\">\n")
            appendCard("Total findings", result.stats.totalVulns.toString(), "total")
            appendCard("Critical", result.stats.criticalCount.toString(), "critical")
            appendCard("High", result.stats.highCount.toString(), "high")
            appendCard("Medium", result.stats.mediumCount.toString(), "medium")
            appendCard("Low", result.stats.lowCount.toString(), "low")
            appendCard("Files scanned", result.stats.filesScanned.toString(), "total")
            appendCard("Lines of code", result.stats.linesOfCode.toString(), "total")
            append("</section>\n")

            if (findings.isEmpty()) {
                append("<p class=\"clean\">No vulnerabilities found. ✔</p>\n")
            } else {
                append("<table>\n<thead><tr>")
                append("<th>Severity</th><th>Rule</th><th>CWE</th><th>OWASP</th><th>Location</th><th>Detail</th>")
                append("</tr></thead>\n<tbody>\n")
                findings.forEach { appendRow(it) }
                append("</tbody>\n</table>\n")
            }

            append("<footer>Generated by VulnSpeed ").append(escape(toolVersion))
            append(" — GPU-Accelerated SAST</footer>\n")
            append("</body>\n</html>\n")
        }
    }

    private fun StringBuilder.appendCard(label: String, value: String, cssClass: String) {
        append("<div class=\"card ").append(cssClass).append("\">")
        append("<span class=\"value\">").append(escape(value)).append("</span>")
        append("<span class=\"label\">").append(escape(label)).append("</span></div>\n")
    }

    private fun StringBuilder.appendRow(v: Vulnerability) {
        append("<tr>")
        append("<td><span class=\"badge ").append(severityClass(v.severity)).append("\">")
        append(v.severity.name).append("</span></td>")
        append("<td>").append(escape(v.ruleName)).append("<br><code class=\"rule\">")
        append(escape(v.ruleId)).append("</code></td>")
        append("<td><a href=\"https://cwe.mitre.org/data/definitions/").append(v.cwe)
        append(".html\">CWE-").append(v.cwe).append("</a></td>")
        append("<td>").append(escape(v.owasp)).append("</td>")
        append("<td><code>").append(escape(v.filePath)).append(":").append(v.line).append("</code></td>")
        append("<td>").append(escape(v.message))
        if (v.codeSnippet.isNotBlank()) {
            append("<pre>").append(escape(v.codeSnippet)).append("</pre>")
        }
        append("</td></tr>\n")
    }

    private fun severityClass(severity: Severity): String = when (severity) {
        Severity.CRITICAL -> "critical"
        Severity.HIGH -> "high"
        Severity.MEDIUM -> "medium"
        Severity.LOW -> "low"
        else -> "info"
    }

    companion object {
        /** Escapes text for safe embedding in HTML. */
        fun escape(text: String): String = buildString(text.length) {
            for (ch in text) {
                when (ch) {
                    '&' -> append("&amp;")
                    '<' -> append("&lt;")
                    '>' -> append("&gt;")
                    '"' -> append("&quot;")
                    '\'' -> append("&#39;")
                    else -> append(ch)
                }
            }
        }

        private val CSS = """
            body{font-family:-apple-system,'Segoe UI',Roboto,sans-serif;margin:0;background:#f6f8fa;color:#1f2328}
            header{background:#0a2a45;color:#fff;padding:24px 32px}
            header h1{margin:0 0 4px;font-size:24px}
            .meta{margin:0;color:#9fb3c8;font-size:13px}
            .cards{display:flex;flex-wrap:wrap;gap:12px;padding:20px 32px}
            .card{background:#fff;border:1px solid #d0d7de;border-radius:8px;padding:12px 20px;min-width:96px;text-align:center}
            .card .value{display:block;font-size:26px;font-weight:700}
            .card .label{font-size:12px;color:#57606a}
            .card.critical .value{color:#cf222e}
            .card.high .value{color:#bc4c00}
            .card.medium .value{color:#9a6700}
            .card.low .value{color:#0969da}
            table{border-collapse:collapse;width:calc(100% - 64px);margin:0 32px 32px;background:#fff;border:1px solid #d0d7de;border-radius:8px}
            th,td{padding:10px 12px;border-bottom:1px solid #d8dee4;text-align:left;font-size:13px;vertical-align:top}
            th{background:#f6f8fa;font-weight:600}
            .badge{display:inline-block;padding:2px 10px;border-radius:12px;font-size:11px;font-weight:700;color:#fff}
            .badge.critical{background:#cf222e}
            .badge.high{background:#bc4c00}
            .badge.medium{background:#9a6700}
            .badge.low{background:#0969da}
            .badge.info{background:#57606a}
            code,pre{font-family:'SF Mono',Menlo,Consolas,monospace;font-size:12px}
            code.rule{color:#57606a}
            pre{background:#f6f8fa;border:1px solid #d8dee4;border-radius:6px;padding:6px 8px;margin:6px 0 0;overflow-x:auto}
            .clean{margin:24px 32px;padding:16px;background:#dafbe1;border:1px solid #aceebb;border-radius:8px;font-weight:600}
            footer{padding:16px 32px;color:#57606a;font-size:12px}
        """.trimIndent()
    }
}
